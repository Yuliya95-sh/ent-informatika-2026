<p><b>INNER JOIN</b> (или просто JOIN) возвращает только строки, для которых нашлась пара в обеих таблицах. <b>LEFT JOIN</b> возвращает все строки левой таблицы, а при отсутствии пары заполняет поля правой таблицы значением NULL.</p>

